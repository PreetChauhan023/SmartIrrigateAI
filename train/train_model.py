"""Train the irrigation model, save locally, write a model card, optionally push to the HF Hub.

Usage:
    python train/train_model.py                       # local only
    HF_TOKEN=xxx python train/train_model.py --push --repo-id <user>/sugarcane-irrigation --version v1
"""
import argparse
import json
import os
import sys
from pathlib import Path

import joblib
from sklearn.ensemble import GradientBoostingClassifier, GradientBoostingRegressor
from sklearn.metrics import accuracy_score, f1_score, mean_absolute_error
from sklearn.model_selection import train_test_split

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from data.generate_data import FEATURES, generate  # noqa: E402

CARD = """---
license: mit
tags: [tabular, agriculture, irrigation, sugarcane, sklearn]
---
# Sugarcane Irrigation Model ({version})

Predicts (a) whether a plot needs irrigation in the next 24h and (b) irrigation duration in hours.

## Training data
SYNTHETIC data generated by `data/generate_data.py` (rule-based labels + noise). Not real farm data.

## Features
{features}

## Metrics (hold-out 20%)
{metrics}

## Intended use
Educational MLOps demo (Hugging Face Hub + LangChain). Output is decision support only;
an agronomist/farmer must confirm (human-in-the-loop).

## Limitations
Trained on synthetic data; will not generalise to real soils/crop varieties without real data.
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--push", action="store_true")
    ap.add_argument("--repo-id", default=os.getenv("HF_MODEL_REPO", ""))
    ap.add_argument("--version", default="v1")
    ap.add_argument("--n", type=int, default=3000)
    a = ap.parse_args()

    df = generate(a.n)
    X = df[FEATURES]
    Xtr, Xte, ctr, cte, dtr, dte = train_test_split(
        X, df.irrigate, df.duration_hours, test_size=0.2, random_state=42, stratify=df.irrigate
    )
    clf = GradientBoostingClassifier(random_state=42).fit(Xtr, ctr)
    # duration regressor trained only on rows that need irrigation
    mask = ctr == 1
    reg = GradientBoostingRegressor(random_state=42).fit(Xtr[mask], dtr[mask])

    pred = clf.predict(Xte)
    on = cte == 1
    metrics = {
        "accuracy": round(accuracy_score(cte, pred), 4),
        "f1": round(f1_score(cte, pred), 4),
        "duration_mae_hours": round(mean_absolute_error(dte[on], reg.predict(Xte[on])), 4),
        "version": a.version,
    }
    print(metrics)

    out = ROOT / "models"
    out.mkdir(exist_ok=True)
    joblib.dump({"clf": clf, "reg": reg, "features": FEATURES, "version": a.version}, out / "irrigation_model.joblib")
    (out / "metrics.json").write_text(json.dumps(metrics, indent=2))
    card = CARD.format(
        version=a.version,
        features="\n".join(f"- `{f}`" for f in FEATURES),
        metrics="\n".join(f"- {k}: {v}" for k, v in metrics.items()),
    )
    (out / "README.md").write_text(card)

    if a.push:
        from huggingface_hub import HfApi

        if not a.repo_id:
            sys.exit("--repo-id required with --push")
        api = HfApi(token=os.getenv("HF_TOKEN"))
        api.create_repo(a.repo_id, exist_ok=True, repo_type="model")
        api.upload_folder(folder_path=str(out), repo_id=a.repo_id, repo_type="model",
                          commit_message=f"model {a.version}")
        api.create_tag(a.repo_id, tag=a.version, repo_type="model", exist_ok=True)
        print(f"Pushed {a.version} to https://huggingface.co/{a.repo_id}")


if __name__ == "__main__":
    main()
